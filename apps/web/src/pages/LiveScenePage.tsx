import { useMemo, useState } from "react";

import { api } from "../api/client";
import { Badge } from "../components/Badge";
import { Button } from "../components/Button";
import { Card, CardBody, CardHeader } from "../components/Card";
import { EmptyState } from "../components/EmptyState";
import { LoadingPanel } from "../components/Loading";
import { PageHeader } from "../components/PageHeader";
import { SceneOverlay } from "../components/SceneOverlay";
import { useApi } from "../hooks/useApi";
import { useApp } from "../hooks/useApp";
import { formatTime, relativeTime } from "../lib/format";

export function LiveScenePage() {
  const { status, latestFrame, socketState, eventsRevision } = useApp();
  const [showTrails, setShowTrails] = useState(true);
  const [showRegions, setShowRegions] = useState(true);

  const regions = useApi(() => api.listRegions(), []);
  const activeEvents = useApi(
    () => api.listEvents({ status: "active", limit: 20 }),
    [eventsRevision],
    { pollMs: 6000 },
  );

  const highlighted = useMemo(() => {
    const set = new Set<string>();
    for (const event of activeEvents.data?.items ?? []) {
      for (const trackId of event.track_ids) set.add(trackId);
    }
    return set;
  }, [activeEvents.data]);

  const pipeline = status?.pipeline;
  const frame = latestFrame;
  const entities = frame?.entities ?? [];
  const tracks = frame?.tracks ?? [];
  const hasSource = pipeline?.mode === "simulated" || pipeline?.mode === "live";

  return (
    <div className="stack" style={{ gap: "var(--sp-5)" }}>
      <PageHeader
        title="Live Scene"
        description="Normalized object overlays, track trails, and configured regions from the active source."
        actions={
          <div className="row">
            <label className="checkbox-row">
              <input
                type="checkbox"
                checked={showTrails}
                onChange={(e) => setShowTrails(e.target.checked)}
              />
              Track trails
            </label>
            <label className="checkbox-row">
              <input
                type="checkbox"
                checked={showRegions}
                onChange={(e) => setShowRegions(e.target.checked)}
              />
              Regions
            </label>
          </div>
        }
      />

      {frame?.is_simulated && (
        <div className="sim-banner" role="note">
          <strong>SIMULATED SOURCE</strong>
          <span>
            Frames are generated by the deterministic demo scenario. Overlays reflect
            synthetic tracks, not real footage.
          </span>
        </div>
      )}

      <div className="grid" style={{ gridTemplateColumns: "minmax(0, 2fr) minmax(280px, 1fr)" }}>
        <Card>
          <CardHeader
            title="Scene workspace"
            subtitle={
              frame
                ? `Frame ${frame.frame_index} · ${formatTime(frame.timestamp)}`
                : "Waiting for frames"
            }
            actions={
              <Badge tone={socketState === "open" ? "ok" : "warn"} dot>
                {socketState === "open" ? "Streaming" : "No stream"}
              </Badge>
            }
          />
          <CardBody>
            <div className="scene-surface">
              <SceneOverlay
                entities={entities}
                tracks={tracks}
                regions={showRegions ? regions.data?.items ?? [] : []}
                showTrails={showTrails}
                highlightedTrackIds={highlighted}
              />
              {!frame && (
                <div className="scene-placeholder">
                  <span className="mono">
                    {hasSource ? "Awaiting first frame..." : "No active source"}
                  </span>
                  <span className="dim" style={{ fontSize: "var(--fs-sm)" }}>
                    Video playback requires a verified PipeGen source. In demo mode only
                    normalized overlays are available.
                  </span>
                </div>
              )}
            </div>
            <p className="dim" style={{ fontSize: "var(--fs-sm)", marginTop: 10 }}>
              Coordinates are normalized image-space fractions in [0,1]. Bounding boxes
              are display overlays only and are never used as evidence on their own.
            </p>
          </CardBody>
        </Card>

        <div className="stack">
          <Card>
            <CardHeader title="Source" />
            <CardBody>
              {pipeline ? (
                <dl className="kv">
                  <dt>Mode</dt>
                  <dd>{pipeline.mode}</dd>
                  <dt>Status</dt>
                  <dd>{pipeline.status.replace(/_/g, " ")}</dd>
                  <dt>Adapter</dt>
                  <dd>{pipeline.adapter}</dd>
                  <dt>Run ID</dt>
                  <dd className="mono truncate">{status?.active_run_id ?? "-"}</dd>
                  <dt>Last frame</dt>
                  <dd>{relativeTime(pipeline.last_successful_frame_at)}</dd>
                </dl>
              ) : (
                <EmptyState title="No source" message="Start a simulated run to begin." />
              )}
            </CardBody>
          </Card>

          <Card>
            <CardHeader
              title="Tracks"
              subtitle={`${tracks.length} active track${tracks.length === 1 ? "" : "s"}`}
            />
            <CardBody>
              {tracks.length === 0 ? (
                <EmptyState title="No tracks" message="Tracks appear once a source is streaming." />
              ) : (
                <div className="stack" style={{ gap: "var(--sp-2)" }}>
                  {tracks.map((track) => {
                    const entity = entities.find((e) => e.track_id === track.track_id);
                    const isFlagged = highlighted.has(track.track_id);
                    return (
                      <div key={track.track_id} className="row-between">
                        <div className="stack" style={{ gap: 0 }}>
                          <span className="mono" style={{ fontSize: "var(--fs-sm)" }}>
                            {track.track_id}
                          </span>
                          <span className="dim" style={{ fontSize: "var(--fs-xs)" }}>
                            {track.class_label}
                            {entity?.confidence != null
                              ? ` · conf ${(entity.confidence * 100).toFixed(0)}%`
                              : ""}
                          </span>
                        </div>
                        {isFlagged ? (
                          <Badge tone="danger">Flagged</Badge>
                        ) : (
                          <Badge tone="neutral">Normal</Badge>
                        )}
                      </div>
                    );
                  })}
                </div>
              )}
            </CardBody>
          </Card>
        </div>
      </div>

      <Card>
        <CardHeader
          title="Active incidents in view"
          subtitle="Tracks involved in active or acknowledged incidents are highlighted"
          actions={
            <Button size="sm" variant="ghost" onClick={activeEvents.reload}>
              Refresh
            </Button>
          }
        />
        <CardBody>
          {activeEvents.loading && !activeEvents.data ? (
            <LoadingPanel rows={2} />
          ) : (activeEvents.data?.items.length ?? 0) === 0 ? (
            <EmptyState title="No active incidents" message="Nothing currently requires attention." />
          ) : (
            <div className="stack" style={{ gap: "var(--sp-2)" }}>
              {activeEvents.data?.items.map((event) => (
                <div key={event.event_id} className="row-between">
                  <div className="stack" style={{ gap: 0 }}>
                    <span>{event.title}</span>
                    <span className="dim mono" style={{ fontSize: "var(--fs-xs)" }}>
                      {event.track_ids.join(", ") || "no tracks"} · {relativeTime(event.last_seen)}
                    </span>
                  </div>
                  <Badge tone={event.is_simulated ? "warn" : "info"}>
                    {event.is_simulated ? "Simulated" : "Observed"}
                  </Badge>
                </div>
              ))}
            </div>
          )}
        </CardBody>
      </Card>
    </div>
  );
}
