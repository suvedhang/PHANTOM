"""Evidence registry.

Tracks the mandatory hackathon submission artifacts. Statuses reflect actual,
recorded state — never a fake "verified" badge. A configured path alone does
NOT mark an artifact verified; an operator must explicitly verify it.
"""

from __future__ import annotations

from sqlalchemy.orm import Session

from .. import repository as repo
from ..schemas import EvidenceStatus

REQUIRED_ARTIFACTS: list[dict[str, object]] = [
    {
        "type": "pipeline_ir_graph",
        "label": "PipeGen Pipeline IR node graph screenshot",
        "required": True,
    },
    {
        "type": "tensorrt_speed_report",
        "label": "TensorRT speed report generated by PipeGen",
        "required": True,
    },
    {
        "type": "live_run",
        "label": "Live pipeline run on supported NVIDIA hardware",
        "required": True,
    },
    {
        "type": "actionable_output",
        "label": "Actionable output demonstrated (JSON/MQTT/alert)",
        "required": True,
    },
    {
        "type": "repo_and_export",
        "label": "Repository link and PipeGen export folder",
        "required": True,
    },
    {
        "type": "model_precision_note",
        "label": "Exact model and precision used in the live run",
        "required": False,
    },
]


def seed_artifacts(session: Session) -> None:
    """Ensure the registry contains the required artifacts (idempotent)."""
    existing_types = {row.type for row in repo.list_artifacts(session)}
    for spec in REQUIRED_ARTIFACTS:
        if spec["type"] in existing_types:
            continue
        repo.upsert_artifact(
            session,
            artifact_id=f"artifact_{spec['type']}",
            type_=str(spec["type"]),
            label=str(spec["label"]),
            path="",
            status=EvidenceStatus.missing.value,
            required=bool(spec["required"]),
        )


def status_summary(session: Session) -> dict[str, object]:
    rows = repo.list_artifacts(session)
    items = [
        {
            "artifact_id": row.artifact_id,
            "type": row.type,
            "label": row.label,
            "path": row.path,
            "status": row.status,
            "required": row.required,
            "notes": row.notes,
            "verified_at": row.verified_at.isoformat() if row.verified_at else None,
        }
        for row in rows
    ]
    required = [i for i in items if i["required"]]
    missing_required = [i for i in required if i["status"] in ("missing", "pending", "invalid")]
    verified_required = [i for i in required if i["status"] == "verified"]
    return {
        "items": items,
        "required_total": len(required),
        "required_verified": len(verified_required),
        "missing_required": len(missing_required),
        "complete": len(missing_required) == 0,
        "note": (
            "Evidence must be captured from the real PipeGen toolchain. "
            "A configured path is not verification."
        ),
    }
